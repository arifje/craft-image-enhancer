'use strict';
const assert = require('node:assert/strict');
const EditorDocument = require('../src/web/assets/imageenhancer/dist/js/editor-document.js');
const doc = new EditorDocument(1200, 800);
assert.equal(doc.dirty, false);
const rectangle = doc.add('rect', { x: 10, y: 20, width: 100, height: 80 });
assert.equal(doc.dirty, true);
assert.equal(doc.hit({x: 50, y: 50}).id, rectangle.id);
const ellipse = doc.add('ellipse', { x: 10, y: 20, width: 100, height: 80 });
assert.equal(doc.hit({x: 50, y: 50}).id, ellipse.id);
doc.reorder(ellipse.id, -1);
assert.equal(doc.hit({x: 50, y: 50}).id, rectangle.id);
rectangle.locked = true;
assert.equal(doc.hit({x: 50, y: 50}).id, ellipse.id);
ellipse.visible = false;
assert.equal(doc.hit({x: 50, y: 50}), undefined);
doc.commit(); doc.undo();
assert.equal(doc.layers.find(x => x.id === ellipse.id).visible, true);
doc.redo();
assert.equal(doc.layers.find(x => x.id === ellipse.id).visible, false);
const copy = doc.duplicate(rectangle.id);
assert.notEqual(copy.id, rectangle.id);
assert.equal(copy.x, 30);
doc.remove(copy.id); assert.equal(doc.layers.length, 2);
doc.undo(); assert.equal(doc.layers.length, 3);
doc.add('text'); assert.equal(doc.cursor, doc.history.length - 1);
doc.layers = [];
const rotated = doc.add('rect', { x: 100, y: 100, width: 200, height: 50, rotation: 90 });
assert.equal(doc.hit({x: 200, y: 40}).id, rotated.id);
assert.equal(doc.hit({x: 110, y: 120}), undefined);
doc.baseId = 'ai-result'; doc.commit(); doc.undo(); assert.equal(doc.baseId, 'original'); doc.redo(); assert.equal(doc.baseId, 'ai-result');
for (let i = 0; i < 90; i++) { doc.layers[0].x = i; doc.commit(); }
assert.equal(doc.history.length, 60);
const capped = new EditorDocument(100, 100); for (let i = 0; i < 40; i++) capped.add('rect'); assert.throws(() => capped.add('rect'), /40 layers/);
console.log('Editor document history, stacking, hit testing, rotation and limits passed.');
